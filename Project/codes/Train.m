function [W_csp, W_lda, thr, rule] = Train(one, all, num)
    one = one - mean(one, [2, 3]);
    all = all - mean(all, [2, 3]);
    N1 = size(one, 3);
    N2 = size(all, 3);
    Rx_1 = mean(pagemtimes(one, pagetranspose(one)), 3);
    Rx_2 = mean(pagemtimes(all, pagetranspose(all)), 3);
    [U, D] = eig(Rx_1, Rx_2);
    [~ , order] = sort(diag(D), 'descend');
    U = U(:,order);
    W_csp = U ./ sqrt(trace(U*U.'));
    W_csp = [W_csp(:, 1:num) W_csp(:, end-(num+1):end)];
    W1_imp = pagemtimes(W_csp.', one);
    W2_imp = pagemtimes(W_csp.', all);
    x_1 = var(W1_imp, 0, 2);
    x_1 = reshape(x_1, [], N1);
    x_2 = var(W2_imp, 0, 2);
    x_2 = reshape(x_2, [], N2);
    mu_1 = mean(x_1, 2);
    mu_2 = mean(x_2, 2);
    sigma_1 = ((x_1 - mu_1) * (x_1 - mu_1).') ./ N1;
    sigma_2 = ((x_2 - mu_2) * (x_2 - mu_2).') ./ N2;
    a = (mu_1 - mu_2) * (mu_1 - mu_2).';
    b = sigma_1 + sigma_2;
    [U, D] = eig(a, b);
    [~ , order] = sort(diag(D), 'descend');
    U = U(:,order);
    W_lda = U ./ sqrt(trace(U*U.'));
    W_lda = W_lda(:, 1);
    Mu1 = W_lda.' * mu_1;
    Mu2 = W_lda.' * mu_2;
    thr = (Mu1 + Mu2) / 2;
    rule = (Mu2 < Mu1) + 1;
end